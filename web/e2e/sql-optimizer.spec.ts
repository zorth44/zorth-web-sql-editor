import { expect, test, type Page } from '@playwright/test'

async function login(page: Page, target = '/sql-optimizer') {
  await page.goto(target)
  await expect(page).toHaveURL(/\/login\?redirect=/)
  await page.getByLabel('用户名').fill('normal')
  await page.getByLabel('密码').fill('optimizer-e2e-secret')
  await page.getByRole('button', { name: '登录', exact: true }).click()
  await expect(page).toHaveURL(new RegExp(`${target.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}$`))
}
async function fillTask(page: Page, name: string) {
  await page.getByLabel('任务名称（可选）').fill(name)
  await page.getByRole('combobox', { name: '数据源', exact: true }).selectOption('ds-orders-a')
  await page.getByLabel('数据库 / 命名空间').selectOption('orders')
  await page.locator('.monaco-editor').click({ position: { x: 120, y: 20 } })
  await page.keyboard.press('Control+A')
  await page.keyboard.insertText('select * from orders')
}
test.describe('SQL optimizer Mock acceptance', () => {
  test('mobile navigation and creation form fit a narrow viewport', async ({ page }) => {
    await page.setViewportSize({ width: 390, height: 844 })
    await login(page)
    await expect(page.getByRole('link', { name: 'SQL 优化器', exact: true })).toBeVisible()
    await fillTask(page, '移动端扫描')
    expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(390)
    await page.screenshot({ path: '/private/tmp/sql-optimizer-mobile.png', fullPage: true })
    await page.getByRole('button', { name: '提交扫描' }).click()
    await expect(page).toHaveURL(/\/sql-optimizer\/tasks\//)
    await expect(page.getByRole('heading', { name: '移动端扫描' })).toBeVisible()
  })
  test('submit, leave, return, report, refresh and retry with a new ID', async ({ page }) => {
    await login(page)
    await fillTask(page, '浏览器扫描')
    await page.getByRole('button', { name: '提交扫描' }).click()
    await expect(page).toHaveURL(/\/sql-optimizer\/tasks\//)
    const original = page.url()
    await expect(
      page.getByText('任务已提交，可稍后在扫描任务中查看报告。离开页面无需保持连接。'),
    ).toBeVisible()
    await page.getByRole('link', { name: '数据源管理' }).click()
    await page.getByRole('link', { name: 'SQL 优化器', exact: true }).click()
    await expect(page.getByRole('link', { name: '浏览器扫描', exact: true })).toBeVisible()
    await page.getByRole('link', { name: '浏览器扫描', exact: true }).click()
    await expect(page.getByRole('heading', { name: '总体结论' })).toBeVisible({ timeout: 12000 })
    await expect(page.getByText('性能严重度：HIGH')).toBeVisible()
    await expect(page.getByRole('heading', { name: '证据缺口 / 未作结论（1）' })).toBeVisible()
    await page.getByRole('button', { name: '定位问题 policy-1', exact: true }).click()
    await expect(page.locator('[data-issue-id="policy-1"]')).toBeFocused()
    await page.reload()
    await expect(page.getByRole('heading', { name: '总体结论' })).toBeVisible()
    await page.getByRole('button', { name: '再次扫描', exact: true }).click()
    await expect(page).not.toHaveURL(original)
    await expect(page.getByRole('link', { name: '原任务' })).toBeVisible()
    await page.getByRole('link', { name: '原任务' }).click()
    await expect(page).toHaveURL(original)
    await expect(page.getByRole('heading', { name: '总体结论' })).toBeVisible()
    await page.setViewportSize({ width: 1280, height: 1700 })
    await page.screenshot({ path: '/private/tmp/sql-optimizer-report.png', fullPage: true })
  })
  test('recovers lost create and retry responses idempotently', async ({ page }) => {
    await login(page)
    await fillTask(page, 'mock:lost')
    await page.getByRole('button', { name: '提交扫描' }).click()
    await expect(page.getByText(/尚未确认是否提交成功/)).toBeVisible()
    await page.getByRole('button', { name: '用原请求找回任务', exact: true }).click()
    await expect(page).toHaveURL(/\/sql-optimizer\/tasks\//)
    await expect(page.getByRole('heading', { name: '总体结论' })).toBeVisible({ timeout: 12000 })
    await page.getByRole('button', { name: '再次扫描', exact: true }).click()
    await expect(page.getByText(/尚未确认重扫是否提交成功/)).toBeVisible()
    await page.getByRole('button', { name: '用原请求找回重扫任务', exact: true }).click()
    await expect(page.getByRole('link', { name: '原任务' })).toBeVisible()
    await page.getByRole('link', { name: '← 返回 SQL 优化器' }).click()
    await expect(page.getByRole('link', { name: 'mock:lost', exact: true })).toHaveCount(2)
    const state = await page.evaluate(() =>
      JSON.stringify({ local: localStorage, session: sessionStorage }),
    )
    expect(state).not.toContain('optimizer-e2e-secret')
    expect(page.url()).not.toContain('select')
  })
  test('401 safely returns to the same detail after login', async ({ page }) => {
    await login(page)
    await fillTask(page, '登录回跳')
    await page.getByRole('button', { name: '提交扫描' }).click()
    await expect(page).toHaveURL(/\/sql-optimizer\/tasks\//)
    const target = new URL(page.url()).pathname
    await page.evaluate(() => sessionStorage.setItem('zorth.sql.token', 'invalid-token'))
    await page.getByRole('button', { name: '刷新任务', exact: true }).click()
    await expect(page).toHaveURL(/\/login\?redirect=/)
    expect(new URL(page.url()).searchParams.get('redirect')).toBe(target)
    await page.getByLabel('用户名').fill('normal')
    await page.getByLabel('密码').fill('optimizer-e2e-secret')
    await page.getByRole('button', { name: '登录', exact: true }).click()
    await expect(page).toHaveURL(new RegExp(`${target}$`))
    await expect(page.getByRole('heading', { name: '登录回跳' })).toBeVisible()
  })
  test('capability absence blocks direct URLs, and invisible task is 404', async ({ page }) => {
    await login(page, '/sql-optimizer/tasks/missing')
    await expect(page.getByText('任务不存在或不可见。')).toBeVisible()
    await page.goto('/sql-optimizer/tasks/mock-forbidden')
    await expect(page.getByText('当前账号没有 SQL 优化器能力。')).toBeVisible()
    await page.evaluate(() => sessionStorage.setItem('zorth.sql.token', 'no-optimize-token'))
    await page.reload()
    await expect(page.getByText('当前账号没有 SQL 优化器能力。')).toBeVisible()
    await expect(page.getByRole('link', { name: 'SQL 优化器', exact: true })).toHaveCount(0)
    await expect(page.getByRole('button', { name: '再次扫描' })).toHaveCount(0)
    await page.goto('/sql-optimizer')
    await expect(page.getByRole('button', { name: '提交扫描' })).toHaveCount(0)
  })
  test('409 and 429 preserve inputs without automatic resubmission', async ({ page }) => {
    await login(page)
    await fillTask(page, 'mock:conflict')
    await page.getByRole('button', { name: '提交扫描' }).click()
    await expect(page.getByText('幂等操作冲突。')).toBeVisible()
    await expect(page.getByLabel('任务名称（可选）')).toHaveValue('mock:conflict')
    await page.getByLabel('任务名称（可选）').fill('mock:quota')
    await page.getByRole('button', { name: '提交扫描' }).click()
    await expect(page.getByText('排队配额已满，请稍后提交。')).toBeVisible()
    await expect(page.getByLabel('数据库 / 命名空间')).toHaveValue('orders')
    await expect(page.getByText('暂无扫描任务。提交一条 SQL 开始分析。')).toBeVisible()
  })
  test('limitations stay visible and credential expiry is a business failure', async ({ page }) => {
    await login(page)
    await fillTask(page, 'mock:limited')
    await page.getByRole('button', { name: '提交扫描' }).click()
    await expect(page.getByText(/存在证据缺口，不能据此判定全部规则通过/)).toBeVisible({
      timeout: 12000,
    })
    await page.getByRole('link', { name: '← 返回 SQL 优化器' }).click()
    await fillTask(page, 'mock:expired')
    await page.getByRole('button', { name: '提交扫描' }).click()
    await expect(page.getByText('后台凭证已过期，请重新登录后再次扫描。')).toBeVisible({
      timeout: 12000,
    })
    await expect(page.getByRole('heading', { name: '总体结论' })).toHaveCount(0)
    await expect(page.getByRole('button', { name: '再次扫描', exact: true })).toBeVisible()
  })
})
